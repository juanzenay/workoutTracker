/**
 * Generates the migration that seeds the bundled catalogue from the vendored
 * free-exercise-db JSON. Re-run after updating vendor/free-exercise-db, and
 * write the output to a NEW migration file (never edit an applied one):
 *
 *   npm run catalogue:build -- supabase/migrations/<timestamp>_seed_catalogue.sql
 *
 * The SQL upserts on (source, source_ref), so applying it again is harmless.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

interface FreeExerciseDbEntry {
  id: string;
  name: string;
  force: string | null;
  level: string;
  mechanic: string | null;
  equipment: string | null;
  primaryMuscles: string[];
  secondaryMuscles: string[];
  instructions: string[];
  category: string;
  images: string[];
}

const out = process.argv[2];
if (!out) {
  console.error("usage: npm run catalogue:build -- <output.sql>");
  process.exit(1);
}

const root = join(import.meta.dirname, "..");
const entries: FreeExerciseDbEntry[] = JSON.parse(
  readFileSync(join(root, "vendor/free-exercise-db/exercises.json"), "utf8"),
);

const rows = entries.map((e) => ({
  source_ref: e.id,
  name: e.name,
  primary_muscles: e.primaryMuscles,
  secondary_muscles: e.secondaryMuscles,
  equipment: e.equipment,
  category: e.category,
  force: e.force,
  level: e.level,
  mechanic: e.mechanic,
  instructions: e.instructions,
  image_paths: e.images,
}));

const json = JSON.stringify(rows);
const tag = "$catalogue$";
if (json.includes(tag)) throw new Error(`catalogue JSON contains ${tag}`);

const sql = `-- Generated by scripts/build-catalogue-migration.ts from vendor/free-exercise-db (${rows.length} exercises). Do not edit.
insert into public.exercises (
  source, source_ref, name, primary_muscles, secondary_muscles, equipment,
  category, force, level, mechanic, instructions, image_paths
)
select
  'free-exercise-db', r.source_ref, r.name, r.primary_muscles, r.secondary_muscles, r.equipment,
  r.category, r.force, r.level, r.mechanic, r.instructions, r.image_paths
from jsonb_to_recordset(${tag}${json}${tag}::jsonb) as r(
  source_ref text, name text, primary_muscles text[], secondary_muscles text[], equipment text,
  category text, force text, level text, mechanic text, instructions text[], image_paths text[]
)
on conflict (source, source_ref) do update set
  name = excluded.name,
  primary_muscles = excluded.primary_muscles,
  secondary_muscles = excluded.secondary_muscles,
  equipment = excluded.equipment,
  category = excluded.category,
  force = excluded.force,
  level = excluded.level,
  mechanic = excluded.mechanic,
  instructions = excluded.instructions,
  image_paths = excluded.image_paths,
  updated_at = now();
`;

writeFileSync(out, sql);
console.log(`wrote ${rows.length} exercises to ${out}`);
